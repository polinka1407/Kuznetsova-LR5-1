# ============================================
# БЛОК 1: ПОДКЛЮЧЕНИЕ НЕОБХОДИМЫХ МОДУЛЕЙ
# ============================================
# Flask - веб-фреймворк для создания сервера
# render_template - функция для отдачи HTML-шаблонов
from flask import Flask, render_template

# ============================================
# БЛОК 2: СОЗДАНИЕ ЭКЗЕМПЛЯРА ПРИЛОЖЕНИЯ FLASK
# ============================================
# __name__ - имя текущего модуля (используется Flask для поиска ресурсов)
app = Flask(__name__)

# ============================================
# БЛОК 3: ОПРЕДЕЛЕНИЕ МАРШРУТОВ (ROUTING)
# ============================================
# Декоратор @app.route связывает URL-адрес с функцией-обработчиком
@app.route('/')  # Корневой URL (например, http://localhost:5000/)
def hello_world():
    # БЛОК 3.1: ОТДАЧА HTML-ШАБЛОНА
    # render_template ищет файл в папке templates/
    return render_template("index.html")

# ============================================
# БЛОК 4: ЗАПУСК СЕРВЕРА
# ============================================
# "0.0.0.0" - сервер слушает все сетевые интерфейсы
# (доступен с любого устройства в локальной сети)
app.run("0.0.0.0")
